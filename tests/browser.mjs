import { chromium } from '@playwright/test';
import { mkdir, writeFile } from 'node:fs/promises';
import assert from 'node:assert/strict';
import { fileURLToPath } from 'node:url';

const review = new URL('../../.impeccable/review/', import.meta.url);
await mkdir(review, { recursive: true });
const browser = await chromium.launch({ channel: 'chrome', headless: true, args: ['--enable-unsafe-swiftshader'] });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, deviceScaleFactor: 1 });
const errors = [];
const badRequests = [];
page.on('pageerror', e => errors.push(e.message));
page.on('console', msg => { if (msg.type() === 'error') errors.push(msg.text()); });
page.on('response', response => { if (response.status() >= 400) badRequests.push({ url: response.url(), status: response.status() }); });
try {
  await page.goto('http://127.0.0.1:5173/', { waitUntil: 'domcontentloaded' });
  await page.waitForFunction(() => window.uodViewer?.state.ready || document.querySelector('#error-state')?.hidden === false, null, { timeout: 90000 });
  const initial = await page.evaluate(() => ({ state: window.uodViewer?.state, error: document.querySelector('#error-message').textContent }));
  console.log('INITIAL', JSON.stringify(initial));
  assert.ok(initial.state?.ready, initial.error);
  await page.waitForFunction(() => window.uodViewer.cloud.displayedPointCount > 10000 || window.uodViewer.state.error, null, { timeout: 90000 });
  await page.waitForFunction(() => !window.uodViewer.cloud.loading && !window.uodViewer.source.loading || window.uodViewer.state.error, null, { timeout: 90000 });
  assert.equal(await page.evaluate(() => window.uodViewer.state.error), null);
  await page.waitForTimeout(500);
  console.log('SURVEY', JSON.stringify(await page.evaluate(() => ({ displayed: window.uodViewer.cloud.displayedPointCount, ...window.uodViewer.state, position: window.uodViewer.instance.view.camera.position.toArray(), target: window.uodViewer.controls.target.toArray() }))));
  await page.screenshot({ path: fileURLToPath(new URL('desktop.png', review)), fullPage: true });
  await page.locator('[data-colour="Z"]').click();
  await page.waitForTimeout(200);
  assert.equal(await page.locator('#legend').isVisible(), true);
  assert.equal(await page.evaluate(() => window.uodViewer.state.colour), 'Z');
  await page.waitForFunction(() => !window.uodViewer.cloud.loading, null, { timeout: 60000 });
  await page.locator('#route-visible').check();
  assert.equal(await page.evaluate(() => window.uodViewer.route.visible), true);
  assert.ok(await page.evaluate(() => window.uodViewer.route.matrixWorld.elements[12] > 339000));
  await page.locator('[data-view="top"]').click();
  await page.waitForTimeout(200);
  await page.waitForFunction(() => !window.uodViewer.cloud.loading, null, { timeout: 60000 });
  await page.screenshot({ path: fileURLToPath(new URL('elevation-route.png', review)), fullPage: true });
  assert.equal(await page.evaluate(() => window.uodViewer.state.view), 'top');
  await page.locator('#quality').selectOption('fast');
  assert.equal(await page.evaluate(() => window.uodViewer.cloud.pointBudget), 1000000);
  await page.locator('#background').selectOption('light');
  assert.equal(await page.evaluate(() => window.uodViewer.instance.engine.clearColor), '#e1e9ed');
  await page.locator('#cloud-visible').uncheck();
  assert.equal(await page.locator('#empty-state').isVisible(), true);
  await page.locator('#show-cloud').click();
  assert.equal(await page.evaluate(() => window.uodViewer.cloud.visible), true);
  await page.locator('#edl').uncheck();
  assert.equal(await page.evaluate(() => window.uodViewer.instance.renderingOptions.enableEDL), false);
  await page.locator('[data-colour="Intensity"]').click();
  assert.equal(await page.locator('#legend-title').textContent(), 'Return intensity');
  await page.locator('#point-size').fill('3');
  assert.equal(await page.evaluate(() => window.uodViewer.cloud.pointSize), 3);
  await page.locator('#fit-button').click();
  assert.equal(await page.evaluate(() => window.uodViewer.state.view), 'full');
  await page.locator('#view').focus();
  await page.keyboard.press('r');
  assert.equal(await page.evaluate(() => window.uodViewer.state.view), 'campus');
  await page.keyboard.press('t');
  assert.equal(await page.evaluate(() => window.uodViewer.state.view), 'top');
  await page.locator('#help-button').click();
  assert.equal(await page.locator('#help-panel').isVisible(), true);
  await page.keyboard.press('Escape');
  assert.equal(await page.locator('#help-panel').isVisible(), false);
  await page.locator('[data-colour="Color"]').click();
  await page.locator('#background').selectOption('slate');
  await page.locator('#route-visible').uncheck();
  await page.locator('#edl').check();
  await page.locator('#quality').selectOption('balanced');
  await page.locator('#point-size').fill('2');
  await page.locator('#reset-button').click();
  await page.waitForTimeout(250);
  const bytesBeforeZoom = await page.evaluate(() => window.uodViewer.state.bytes);
  await page.mouse.move(880, 520);
  await page.mouse.wheel(0, -800);
  await page.waitForFunction(bytes => window.uodViewer.state.bytes > bytes, bytesBeforeZoom, { timeout: 60000 });
  assert.equal(await page.evaluate(() => window.uodViewer.state.view), 'custom');
  console.log('ZOOM_STREAMING', JSON.stringify(await page.evaluate(() => ({ bytes: window.uodViewer.state.bytes, points: window.uodViewer.cloud.displayedPointCount }))));
  await page.setViewportSize({ width: 390, height: 844 });
  await page.waitForFunction(() => Math.abs(window.uodViewer.instance.view.camera.aspect - document.querySelector('#view').clientWidth / document.querySelector('#view').clientHeight) < .01);
  await page.waitForFunction(() => document.querySelector('#sidebar').getBoundingClientRect().right <= 1);
  await page.locator('#reset-button').click();
  await page.waitForTimeout(300);
  assert.equal(await page.evaluate(() => window.uodViewer.state.view), 'campus');
  await page.waitForFunction(() => !window.uodViewer.cloud.loading && !window.uodViewer.source.loading, null, { timeout: 60000 });
  await page.screenshot({ path: fileURLToPath(new URL('mobile.png', review)), fullPage: true });
  await page.getByRole('button', { name: 'Open survey controls', exact: true }).click();
  await page.waitForFunction(() => Math.abs(document.querySelector('#sidebar').getBoundingClientRect().left) < 1);
  assert.equal(await page.locator('#sidebar').evaluate(el => el.classList.contains('open')), true);
  await page.screenshot({ path: fileURLToPath(new URL('mobile-controls.png', review)), fullPage: true });
  await page.locator('#close-panel').click();
  await page.waitForFunction(() => document.querySelector('#sidebar').getBoundingClientRect().right <= 1);
  const overflow = await page.evaluate(() => document.documentElement.scrollWidth > innerWidth);
  assert.equal(overflow, false);
  assert.deepEqual(badRequests, []);
  assert.deepEqual(errors, []);
  const result = { passed: true, controls: ['natural', 'elevation', 'intensity', 'route', 'camera-presets', 'fit-survey', 'point-size', 'quality', 'background', 'depth-enhancement', 'visibility', 'keyboard', 'help', 'mobile-drawer'], errors, badRequests, state: await page.evaluate(() => window.uodViewer.state) };
  await writeFile(new URL('browser-results.json', review), JSON.stringify(result, null, 2));
  console.log('PASS', JSON.stringify(result));
} catch (error) {
  console.log('BROWSER_ERRORS', JSON.stringify(errors));
  console.log('BAD_REQUESTS', JSON.stringify(badRequests));
  await page.screenshot({ path: fileURLToPath(new URL('failure.png', review)), fullPage: true });
  throw error;
} finally { await browser.close(); }
